const BY_CHAR = new Map(RADICALS.map((r) => [r.ch, r]));
// распространённые формы ключей
const ALIASES: Record<string, string> = { 亻: '人', '氵': '水', '扌': '手', '忄': '心', '艹': '艸', '辶': '辵', '刂': '刀', '礻': '示', '衤': '衣', '犭': '犬', '灬': '火', '罒': '网', '王': '玉', '月': '月', '阝': '阜', '耂': '老', '糹': '糸', '訁': '言', '飠': '食', '釒': '金', '戸': '戶', '黄': '黃', '黒': '黑', '麦': '麥', '歯': '齒', '竜': '龍', '亀': '龜', '斉': '齊' };

export function componentInfo(part: string): { show: string; ru: string } | null {
  if (COMPONENT_NAMES[part]) return COMPONENT_NAMES[part];
  const r = BY_CHAR.get(part) ?? BY_CHAR.get(ALIASES[part] ?? '');
  return r ? { show: part, ru: r.ru } : null;
}

export function radicalByNumber(n: number) {
  return RADICALS[n - 1];
}
