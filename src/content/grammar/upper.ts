import type { GrammarTopic, GrammarQuestion } from '../types';

type Ex = [string, string, string?];

function g(
  id: string,
  level: 3 | 2 | 1,
  title: string,
  pattern: string,
  meaning: string,
  text: string,
  examples: Ex[],
  q?: GrammarQuestion,
  note?: string,
): GrammarTopic {
  return {
    id,
    level,
    title,
    pattern,
    meaning,
    explanation: [{ t: 'p', text }, ...(note ? [{ t: 'tip' as const, text: note }] : [])],
    examples: examples.map(([ja, ru, tokens]) => ({ ja, ru, tokens })),
    questions: q ? [q] : [],
  };
}

